function standardOptions(entries) {
  return Object.freeze(entries.map(([value, name]) => Object.freeze({
    value,
    label: `${name} (${value})`,
  })));
}

const COUNTRY_OPTIONS = standardOptions(ISO_3166_1_COUNTRIES);
const CURRENCY_OPTIONS = standardOptions(ISO_4217_CURRENCIES);

function optionsWithCurrent(options, current, type) {
  const code = typeof current === 'string' ? current.trim().toUpperCase() : '';
  if (!code || options.some((option) => option.value === code)) return [...options];

  let name = code;
  try {
    name = new Intl.DisplayNames(['en'], { type }).of(code) ?? code;
  } catch {
    // Keep the exact stored standards code available even in older browsers.
  }
  return [...options, { value: code, label: `${name} (${code})` }];
}

export function countryOptions({ current } = {}) {
  return optionsWithCurrent(COUNTRY_OPTIONS, current, 'region');
}

export function currencyOptions({ current } = {}) {
  return optionsWithCurrent(CURRENCY_OPTIONS, current, 'currency');
}
